// Self-hosts the Google Fonts used by the site: downloads the latin and latin-ext
// WOFF2 files into public/fonts and writes src/styles/fonts.css with matching
// @font-face rules. Re-run after changing FONTS_CSS_URL. Fonts are SIL OFL licensed.
// Usage: node scripts/fetch-fonts.mjs
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const FONTS_CSS_URL =
  'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;0,700;1,400;1,600&family=Playfair+Display:ital,wght@0,400;0,500;0,600;0,700;0,800;1,400;1,600;1,700&family=Plus+Jakarta+Sans:wght@300;400;500;600;700;800&family=Alex+Brush&display=swap';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'public', 'fonts');
const KEEP = new Set(['latin', 'latin-ext']); // latin-ext carries the rupee sign
// A modern desktop UA makes Google serve WOFF2 files.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';

const css = await (await fetch(FONTS_CSS_URL, { headers: { 'User-Agent': UA } })).text();
const blocks = [...css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g)];

await mkdir(outDir, { recursive: true });
const fileForUrl = new Map();
const usedNames = new Set();
const rules = [];

for (const [, subset, body] of blocks) {
  if (!KEEP.has(subset)) continue;
  const get = (prop) => body.match(new RegExp(`${prop}:\s*([^;]+);`))?.[1].trim();
  const family = get('font-family').replace(/['"]/g, '');
  const style = get('font-style');
  const weight = get('font-weight');
  const range = get('unicode-range');
  const url = body.match(/url\(([^)]+)\)/)[1];

  if (!fileForUrl.has(url)) {
    let name = `${family.toLowerCase().replace(/\s+/g, '-')}-${style}-${subset}`;
    if (usedNames.has(name)) name += `-${weight}`;
    usedNames.add(name);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`Download failed (${res.status}): ${url}`);
    await writeFile(path.join(outDir, `${name}.woff2`), Buffer.from(await res.arrayBuffer()));
    fileForUrl.set(url, name);
  }

  rules.push(
    `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('/fonts/${fileForUrl.get(url)}.woff2') format('woff2');\n  unicode-range: ${range};\n}`
  );
}

const header = '/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n\n';
await writeFile(path.join(root, 'src', 'styles', 'fonts.css'), header + rules.join('\n\n') + '\n');
console.log(`done: ${fileForUrl.size} font files, ${rules.length} @font-face rules`);
